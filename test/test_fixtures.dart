  /// Builds one fixture item with a deterministic checksum (SHA-256
  /// of `id|timestamp`, via the public byte-checksum helper — test
  /// data only, never provenance). Shared by tests that build their
  /// own small archives.
  static MemoryItem item({
    required String id,
    required MediaKind kind,
    required String title,
    required DateTime takenAt,
    String? storyId,
    String? chapterId,
    List<String> tags = const <String>[],
    List<String> personIds = const <String>[],
    String? placeId,
    String aspectRatio = '4:3',
    int widthPx = 0,
    int heightPx = 0,
    int? durationSeconds,
    String? note,
    bool isDemo = false,
  }) =>
      MemoryItem(
        id: id,
        kind: kind,
        title: title,
        takenAt: takenAt,
        checksum: MemoryItem.checksumOfBytes(
          utf8.encode('$id|${takenAt.toIso8601String()}'),
        ),
        storyId: storyId,
        chapterId: chapterId,
        tags: tags,
        personIds: personIds,
        placeId: placeId,
        aspectRatio: aspectRatio,
        widthPx: widthPx,
        heightPx: heightPx,
        durationSeconds: durationSeconds,
        note: note,
        isDemo: isDemo,
      );
}
