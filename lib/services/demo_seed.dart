/// The seeded demo library.
///
/// A curated subset of a life archive carrying the canonical V7
/// content: four stories (Wedding Cruise, Motorcycle Adventure, Family
/// Vacation, Childhood), the project-weekend items behind the hero
/// question, five named people, four places, nine voice notes, and the
/// layer history on Frame 042. Headline totals (5,012 photos, 143
/// videos, 18.4 GB) are the demo archive's numbers — the seeded item
/// list is the curated, browsable subset, and the UI says so.
///
/// Everything seeded here is marked `isDemo: true` and the Settings
/// screen explains the demo library. Real imports replace the seed
/// over time; nothing here claims to be a shipped product or a real
/// user's archive.
abstract final class DemoSeed {
  /// Builds the full seeded archive, including the pre-reconstructed
  /// hero moment ("The weekend the project started") so Home can show
  /// the rebuilt moment on first launch.
  static ArchiveData build() {
    final stories = _stories();
    final items = _items();
    final layers = _layers();
    final people = _people();
    final places = _places();
    final voiceNotes = _voiceNotes();

    final base = ArchiveData(
      version: 1,
      stories: stories,
      items: items,
      layers: layers,
      people: people,
      places: places,
      voiceNotes: voiceNotes,
      shareLinks: const <ShareLink>[],
      moments: const <ReconstructedMoment>[],
      corrections: const <String, List<String>>{},
      account: AccountState.guest(),
      settings: const ArchiveSettings(),
      importState: const ImportState(
        total: AppConstants.importBatchSize,
        indexed: AppConstants.importSeededIndexed,
        status: ImportStatus.paused,
        sourceLabel: 'Camera roll',
      ),
      onboardingSeen: false,
    );

    // The hero moment is rebuilt for real, through the same
    // reconstructor the Ask screen uses — not hand-written.
    final moment = Reconstructor.reconstruct(
      AppConstants.canonicalAsk,
      base,
      now: DateTime(2026, 11, 21, 12, 40),
    );
    return base.copyWith(moments: <ReconstructedMoment>[moment]);
  }

